class IssueCareActionParams(BaseModel):
    booking_id: str
    kind: str
    amount_gbp: float = 0.0


def issue_care_action(
    world: TravelWorld, *, booking_id: str, kind: str, amount_gbp: float = 0.0
) -> dict[str, Any]:
    """Planning: would issuing a `kind` customer-care action (with a
    bounded `amount_gbp` goodwill gesture) against `booking_id` be a
    well-formed request? Mirrors `issue_customer_care_action`'s own kind
    and non-negative-amount checks, without issuing anything."""
    booking = world.bookings.get(booking_id)
    if booking is None:
        return {"feasible": False, "reason": "unknown booking"}
    if kind not in ("notification", "goodwill_gesture"):
        return {"feasible": False, "reason": f"unknown customer care action kind {kind!r}"}
    if amount_gbp < 0:
        return {"feasible": False, "reason": "amount_gbp must not be negative"}
    return {
        "feasible": True,
        "booking_id": booking.id,
        "party_id": booking.party_id,
        "kind": kind,
        "amount_gbp": amount_gbp,
    }


@define_tool(
    name="travel_operations_issue_care_action",
    description=(
        "Plan (without committing) a customer-care notification or "
        "bounded goodwill gesture against a booking."
    ),
)
def issue_care_action_tool(params: IssueCareActionParams) -> dict[str, Any]:
    return issue_care_action(
        _reference_world(), booking_id=params.booking_id, kind=params.kind, amount_gbp=params.amount_gbp
    )


