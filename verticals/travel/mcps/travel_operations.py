class CheckFlightDisruptionParams(BaseModel):
    flight_id: str


def check_flight_disruption(world: TravelWorld, flight_id: str) -> dict[str, Any]:
    """Query: a flight's status, any open cancellation disruption tied to
    it, and how many live bookings it affects."""
    flight = world.flights.get(flight_id)
    if flight is None:
        return {"found": False, "flight_id": flight_id, "reason": "unknown flight"}
    open_disruption = next(
        (
            disruption
            for disruption in world.disruptions.values()
            if disruption.resource_id == flight_id
            and disruption.kind == "flight_cancellation"
            and disruption.status == "reported"
        ),
        None,
    )
    affected_booking_ids = sorted(
        booking.id
        for booking in world.bookings.values()
        if booking.flight_id == flight_id and booking.status in ("confirmed", "deposit_paid", "paid")
    )
    return {
        "found": True,
        "flight_id": flight.id,
        "status": flight.status,
        "open_disruption_id": open_disruption.id if open_disruption else None,
        "affected_booking_ids": affected_booking_ids,
        "affected_booking_count": len(affected_booking_ids),
    }


@define_tool(
    name="travel_operations_check_flight_disruption",
    description=(
        "Check a flight's status, any open cancellation disruption tied "
        "to it, and the live bookings it would strand if cancelled."
    ),
)
def check_flight_disruption_tool(params: CheckFlightDisruptionParams) -> dict[str, Any]:
    return check_flight_disruption(_reference_world(), params.flight_id)


class ReaccommodateBookingParams(BaseModel):
    booking_id: str
    to_flight_id: str
    to_transfer_id: str


def reaccommodate_booking(
    world: TravelWorld, *, booking_id: str, to_flight_id: str, to_transfer_id: str
) -> dict[str, Any]:
    """Planning: would reaccommodating `booking_id` onto the replacement
    flight/transfer be feasible? Mirrors `reaccommodate_travellers`'s own
    capacity checks exactly, without moving anything."""
    booking = world.bookings.get(booking_id)
    if booking is None:
        return {"feasible": False, "reason": "unknown booking"}
    to_flight = world.flights.get(to_flight_id)
    to_transfer = world.transfers.get(to_transfer_id)
    if to_flight is None or to_transfer is None:
        return {"feasible": False, "reason": "unknown replacement flight or transfer"}
    party = world.parties.get(booking.party_id)
    if party is None:
        return {"feasible": False, "reason": "unknown travelling party"}
    flight_ok = to_flight.reserved + party.size <= to_flight.capacity
    transfer_ok = to_transfer.reserved + party.size <= to_transfer.capacity
    return {
        "feasible": flight_ok and transfer_ok,
        "flight_capacity_ok": flight_ok,
        "transfer_capacity_ok": transfer_ok,
        "party_size": party.size,
        "flight_headroom": to_flight.capacity - to_flight.reserved,
        "transfer_headroom": to_transfer.capacity - to_transfer.reserved,
    }


@define_tool(
    name="travel_operations_reaccommodate_booking",
    description=(
        "Plan (without committing) whether a booking's travelling party "
        "would fit a replacement flight and transfer's remaining "
        "capacity."
    ),
)
def reaccommodate_booking_tool(params: ReaccommodateBookingParams) -> dict[str, Any]:
    return reaccommodate_booking(
        _reference_world(),
        booking_id=params.booking_id,
        to_flight_id=params.to_flight_id,
        to_transfer_id=params.to_transfer_id,
    )


