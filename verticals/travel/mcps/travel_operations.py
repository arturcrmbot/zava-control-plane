class CheckAllotmentHeadroomParams(BaseModel):
    allotment_id: str


def check_allotment_headroom(world: TravelWorld, allotment_id: str) -> dict[str, Any]:
    """Query: an allotment's donor headroom (`allotment - reserved`) and
    recipient headroom (`total - allotment`) -- the same two formulas
    `adjust_package_allotment` / `move_hotel_allotment` check before
    moving rooms."""
    allotment = world.allotments.get(allotment_id)
    if allotment is None:
        return {"found": False, "allotment_id": allotment_id, "reason": "unknown allotment"}
    conserved = 0 <= allotment.occupied <= allotment.reserved <= allotment.allotment <= allotment.total
    utilisation_pct = (
        round(100.0 * allotment.reserved / allotment.allotment, 2) if allotment.allotment else 0.0
    )
    return {
        "found": True,
        "allotment_id": allotment.id,
        "total": allotment.total,
        "allotment": allotment.allotment,
        "reserved": allotment.reserved,
        "occupied": allotment.occupied,
        "donor_headroom": allotment.allotment - allotment.reserved,
        "recipient_headroom": allotment.total - allotment.allotment,
        "utilisation_pct": utilisation_pct,
        "conservation_holds": conserved,
    }


@define_tool(
    name="travel_operations_check_allotment_headroom",
    description=(
        "Check a hotel room allotment's donor headroom (spare contracted "
        "rooms it could give away) and recipient headroom (contracted "
        "total it could still absorb), plus its utilisation percentage."
    ),
)
def check_allotment_headroom_tool(params: CheckAllotmentHeadroomParams) -> dict[str, Any]:
    return check_allotment_headroom(_reference_world(), params.allotment_id)


class MoveAllotmentRoomsParams(BaseModel):
    from_allotment_id: str
    to_allotment_id: str
    rooms: int


def move_allotment_rooms(
    world: TravelWorld, *, from_allotment_id: str, to_allotment_id: str, rooms: int
) -> dict[str, Any]:
    """Planning: would moving `rooms` from the donor to the recipient
    allotment be feasible? Mirrors `adjust_package_allotment` /
    `move_hotel_allotment`'s own two headroom checks exactly, without
    moving anything."""
    donor = world.allotments.get(from_allotment_id)
    recipient = world.allotments.get(to_allotment_id)
    if donor is None or recipient is None:
        return {"feasible": False, "reason": "unknown donor or recipient allotment"}
    donor_headroom = donor.allotment - donor.reserved
    recipient_headroom = recipient.total - recipient.allotment
    donor_ok = rooms <= donor_headroom
    recipient_ok = rooms <= recipient_headroom
    feasible = donor_ok and recipient_ok
    return {
        "feasible": feasible,
        "donor_ok": donor_ok,
        "recipient_ok": recipient_ok,
        "donor_headroom": donor_headroom,
        "recipient_headroom": recipient_headroom,
        "resulting_donor_allotment": donor.allotment - rooms if donor_ok else donor.allotment,
        "resulting_recipient_allotment": (
            recipient.allotment + rooms if recipient_ok else recipient.allotment
        ),
    }


@define_tool(
    name="travel_operations_move_allotment_rooms",
    description=(
        "Plan (without committing) whether moving a room count from a "
        "donor to a recipient hotel allotment would respect both the "
        "donor's headroom and the recipient's contracted total."
    ),
)
def move_allotment_rooms_tool(params: MoveAllotmentRoomsParams) -> dict[str, Any]:
    return move_allotment_rooms(
        _reference_world(),
        from_allotment_id=params.from_allotment_id,
        to_allotment_id=params.to_allotment_id,
        rooms=params.rooms,
    )


