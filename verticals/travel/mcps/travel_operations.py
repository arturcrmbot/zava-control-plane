class CheckQuoteOfferParams(BaseModel):
    quote_id: str


def check_quote_offer(world: TravelWorld, quote_id: str) -> dict[str, Any]:
    """Query: a quote's current offer state (mirrors
    `confirm_package_booking`'s own quote checks)."""
    quote = world.quotes.get(quote_id)
    if quote is None:
        return {"found": False, "quote_id": quote_id, "reason": "unknown quote"}
    return {
        "found": True,
        "quote_id": quote.id,
        "status": quote.status,
        "price": quote.price,
        "party_id": quote.party_id,
        "customer_id": quote.customer_id,
        "adviser_id": quote.adviser_id,
        "ready_to_confirm": quote.status == "offered" and quote.price is not None,
    }


@define_tool(
    name="travel_operations_check_quote_offer",
    description=(
        "Check a holiday quote's current offer state (status, price, "
        "party) and whether it is ready to be confirmed into a booking."
    ),
)
def check_quote_offer_tool(params: CheckQuoteOfferParams) -> dict[str, Any]:
    return check_quote_offer(_reference_world(), params.quote_id)


class ReservePackageCapacityParams(BaseModel):
    flight_id: str
    allotment_id: str
    transfer_id: str
    party_size: int
    rooms: int


def reserve_package_capacity(
    world: TravelWorld,
    *,
    flight_id: str,
    allotment_id: str,
    transfer_id: str,
    party_size: int,
    rooms: int,
) -> dict[str, Any]:
    """Planning: would a party of `party_size` and `rooms` rooms fit this
    flight/allotment/transfer? Mirrors `confirm_package_booking`'s own
    three capacity checks exactly, without reserving anything."""
    flight = world.flights.get(flight_id)
    allotment = world.allotments.get(allotment_id)
    transfer = world.transfers.get(transfer_id)
    if flight is None or allotment is None or transfer is None:
        return {"feasible": False, "reason": "unknown flight, allotment or transfer"}
    flight_ok = flight.reserved + party_size <= flight.capacity
    allotment_ok = allotment.reserved + rooms <= allotment.allotment
    transfer_ok = transfer.reserved + party_size <= transfer.capacity
    feasible = flight_ok and allotment_ok and transfer_ok
    return {
        "feasible": feasible,
        "flight_capacity_ok": flight_ok,
        "allotment_capacity_ok": allotment_ok,
        "transfer_capacity_ok": transfer_ok,
        "flight_headroom": flight.capacity - flight.reserved,
        "allotment_headroom": allotment.allotment - allotment.reserved,
        "transfer_headroom": transfer.capacity - transfer.reserved,
    }


@define_tool(
    name="travel_operations_reserve_package_capacity",
    description=(
        "Plan (without committing) whether a party and room count would "
        "fit a flight, hotel allotment and transfer's remaining capacity."
    ),
)
def reserve_package_capacity_tool(params: ReservePackageCapacityParams) -> dict[str, Any]:
    return reserve_package_capacity(
        _reference_world(),
        flight_id=params.flight_id,
        allotment_id=params.allotment_id,
        transfer_id=params.transfer_id,
        party_size=params.party_size,
        rooms=params.rooms,
    )


