class CheckBookingStatusParams(BaseModel):
    booking_id: str


def check_booking_status(world: TravelWorld, booking_id: str) -> dict[str, Any]:
    """Query: a booking's current status plus its payment and refund
    history -- shared by cancellation-refund, payment-exception and
    proactive-customer-care, which all act on a booking's live state."""
    booking = world.bookings.get(booking_id)
    if booking is None:
        return {"found": False, "booking_id": booking_id, "reason": "unknown booking"}
    payments = sorted(
        (payment.id for payment in world.payments.values() if payment.booking_id == booking_id),
    )
    refunds = sorted(
        (refund.id for refund in world.refunds.values() if refund.booking_id == booking_id),
    )
    paid_to_date = sum(
        payment.amount for payment in world.payments.values() if payment.booking_id == booking_id
    )
    return {
        "found": True,
        "booking_id": booking.id,
        "status": booking.status,
        "total_price": booking.total_price,
        "paid_to_date": paid_to_date,
        "outstanding_balance": booking.total_price - paid_to_date,
        "party_id": booking.party_id,
        "flight_id": booking.flight_id,
        "allotment_id": booking.allotment_id,
        "transfer_id": booking.transfer_id,
        "payment_ids": payments,
        "refund_ids": refunds,
    }


@define_tool(
    name="travel_operations_check_booking_status",
    description=(
        "Check a booking's current status, outstanding balance and its "
        "payment/refund history."
    ),
)
def check_booking_status_tool(params: CheckBookingStatusParams) -> dict[str, Any]:
    return check_booking_status(_reference_world(), params.booking_id)


class ReleaseBookingCapacityParams(BaseModel):
    booking_id: str


def release_booking_capacity(world: TravelWorld, booking_id: str) -> dict[str, Any]:
    """Planning: what flight/allotment/transfer capacity would be freed
    if `booking_id` were cancelled or released? Mirrors
    `cancel_and_refund_booking` / `resolve_payment_exception`'s own
    release maths exactly, without releasing anything."""
    booking = world.bookings.get(booking_id)
    if booking is None:
        return {"feasible": False, "reason": "unknown booking"}
    if booking.status == "cancelled":
        return {
            "feasible": False,
            "reason": "booking already cancelled: capacity already released",
            "already_cancelled": True,
        }
    party = world.parties.get(booking.party_id)
    party_size = party.size if party is not None else 0
    return {
        "feasible": True,
        "booking_id": booking.id,
        "flight_id": booking.flight_id,
        "allotment_id": booking.allotment_id,
        "transfer_id": booking.transfer_id,
        "would_release_flight_seats": party_size,
        "would_release_hotel_rooms": booking.rooms,
        "would_release_transfer_seats": party_size,
    }


@define_tool(
    name="travel_operations_release_booking_capacity",
    description=(
        "Plan (without committing) the flight, hotel allotment and "
        "transfer capacity that would be released if a booking were "
        "cancelled or its payment exception resolved by release."
    ),
)
def release_booking_capacity_tool(params: ReleaseBookingCapacityParams) -> dict[str, Any]:
    return release_booking_capacity(_reference_world(), params.booking_id)


