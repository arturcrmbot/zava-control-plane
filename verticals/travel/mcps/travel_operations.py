"""Travel: real deterministic query/mutation-planning MCP operations
(generated by verticals.travel.generator.mcp_templates).

Every tool below reads `TravelWorld` state (or computes a feasibility
plan for a proposed command) without ever mutating it: the sole
authoritative, journal-backed mutation path for the eight processes is
`verticals.travel.actions.commands.COMMAND_HANDLERS`. No tool here calls
out to a network or external system -- every result is a pure function
of the `TravelWorld` snapshot passed to (or freshly built by) it.

Do not hand-edit -- change verticals.travel.generator.mcp_templates and
regenerate via `uv run python -m verticals.travel.generator`.
"""
from __future__ import annotations

from collections.abc import Callable
from typing import Any

from copilot.tools import define_tool
from pydantic import BaseModel

from verticals.travel.worlds.scenario import TravelWorld

# A fresh, deterministic (seed=42) reference world, built lazily and
# reused for every tool call that is not explicitly bound to its own
# world instance. Deterministic and side-effect-free: every call reads
# the same actor layout `worlds/reference_data.py` seeds.
_DEFAULT_SEED = 42
_default_world: TravelWorld | None = None


def _reference_world() -> TravelWorld:
    global _default_world
    if _default_world is None:
        _default_world = TravelWorld(seed=_DEFAULT_SEED)
    return _default_world


