class DispatchReplacementTransferParams(BaseModel):
    transfer_id: str


def dispatch_replacement_transfer(world: TravelWorld, transfer_id: str) -> dict[str, Any]:
    """Planning: the replacement transfer id `dispatch_replacement_transfer`
    would create or reuse (`TRF-REPL-<transfer_id>`, the exact convention
    the real command handler uses), and whether one already exists."""
    transfer = world.transfers.get(transfer_id)
    if transfer is None:
        return {"feasible": False, "reason": "unknown transfer"}
    replacement_id = f"TRF-REPL-{transfer_id}"
    existing = world.transfers.get(replacement_id)
    return {
        "feasible": True,
        "transfer_id": transfer.id,
        "planned_replacement_id": replacement_id,
        "replacement_already_exists": existing is not None,
        "replacement_status": existing.status if existing is not None else None,
    }


