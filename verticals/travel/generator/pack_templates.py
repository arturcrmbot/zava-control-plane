def _load_durable_module():
    return import_module("verticals.travel.durable")


def build_pack() -> VerticalPack:
    orchestrators = frozenset(
        domain.orchestrator_name for domain in TRAVEL_DOMAINS.values() if not domain.stub
    )
    return VerticalPack(
        root=PACK_ROOT,
        name="travel",
        display_name="Travel",
        manifest_version="1",
        domains=dict(TRAVEL_DOMAINS),
        organisation_functions=dict(TRAVEL_FUNCTIONS),
        agents=dict(TRAVEL_AGENTS),
        authority=dict(TRAVEL_AUTHORITY),
        personas=dict(TRAVEL_PERSONAS),
        policy_sources=(PACK_ROOT / "policies" / "tools.yaml",),
        durable_functions=DurableFunctionRegistration(
            load_module=_load_durable_module,
            orchestrators=orchestrators,
            activities=frozenset(),
        ),
        personae_roots=(PACK_ROOT / "personae",),
        skill_roots=(PACK_ROOT / "skills",),
        mcp_modules=("verticals.travel.mcps.travel_operations",),
        external_capabilities=TRAVEL_EXTERNAL_CAPABILITIES,
        worlds=dict(TRAVEL_WORLDS),
        default_world="travel",
        seed=SeedRegistration(bootstrap=bootstrap),
        projections={_KNOWLEDGE_WORKFLOW_TYPE: _project_knowledge},
        memory_workflow_types=(_KNOWLEDGE_WORKFLOW_TYPE,),
        lifecycle=LifecycleRegistration(start=start),
        recordings=RecordingSources(curated_dirs=()),
        ui=load_ui_manifest(PACK_ROOT / "ui.json"),
        ramp_workflow_types=(),
        workflow_detail_hook=workflow_detail,
    )
