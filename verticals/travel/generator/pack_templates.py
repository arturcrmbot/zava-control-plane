"""Hand-authored source templates for the Travel pack's manifest surface.

Renders the nine pack-manifest modules from `verticals.travel.generator.
portfolio`'s `PROCESS_SPECS` / `FUNCTION_SPECS` / `AUTHORITY_SPECS` /
`AGENT_SPECS` (the single declarative source of truth): `manifest.py`,
`domains.py`, `functions.py`, `authority.py`, `personas.py`, `agents.py`,
`seed.py`, `lifecycle.py` and `ui.json`. Every rendered `.py` module is
fully self-contained (no runtime import of `verticals.travel.generator`)
and depends only on the shared, industry-neutral `api.shared.*` contracts
and the cross-vertical `verticals._helpers` module (used by every existing
vertical pack, not Travel-specific).

This module is generated by verticals.travel.generator.pack_templates.
Do not hand-edit the rendered files -- change this module (or
`portfolio.py`) and regenerate via `uv run python -m verticals.travel.generator`.
"""
from __future__ import annotations

import json

from verticals.travel.generator.portfolio import (
    AGENT_SPECS,
    AUTHORITY_SPECS,
    FUNCTION_SPECS,
    HERO_WORKFLOW_TYPES,
    PROCESS_SPECS,
)


def render_functions_py() -> str:
    """Render `functions.py`: the six organisation `Function` rows."""
    lines = [
        '"""Travel: the six organisation functions grouping the eight-process',
        'portfolio (generated by verticals.travel.generator.pack_templates).',
        "",
        "Do not hand-edit -- change the generator template (or",
        "verticals.travel.generator.portfolio) and regenerate via",
        "`uv run python -m verticals.travel.generator`.",
        '"""',
        "from __future__ import annotations",
        "",
        "from api.shared.function_contracts import Function, PersonaTree",
        "",
        "TRAVEL_FUNCTIONS: dict[str, Function] = {",
    ]
    for spec in FUNCTION_SPECS:
        ambient_agents = tuple(
            agent.agent_id for agent in AGENT_SPECS if agent.scope_function == spec.name
        )
        lines.append(f"    {spec.name!r}: Function(")
        lines.append(f"        name={spec.name!r},")
        lines.append(f"        display={spec.display!r},")
        lines.append(f"        operator_surface={spec.operator_surface!r},")
        lines.append(f"        owns_domains={spec.owns_workflow_types!r},")
        lines.append(f"        ambient_agents={ambient_agents!r},")
        lines.append(f"        kpis={spec.kpis!r},")
        lines.append("        persona_hierarchy=PersonaTree(")
        lines.append(f"            role={spec.head_role!r},")
        process_children = ", ".join(f"PersonaTree(role={role!r})" for role in spec.process_roles)
        trailing_comma = "," if len(spec.process_roles) == 1 else ""
        lines.append(f"            manages=({process_children}{trailing_comma}),")
        lines.append("        ),")
        lines.append("    ),")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


_FUNCTION_OPERATOR_SURFACE_BY_NAME = {spec.name: spec.operator_surface for spec in FUNCTION_SPECS}


def _operator_surface_for(spec) -> str:
    """The owning function's `operator_surface`, for a Domain row."""
    return _FUNCTION_OPERATOR_SURFACE_BY_NAME[spec.function]


def render_domains_py() -> str:
    """Render `domains.py`: the eight `Domain` rows, wired to their function."""
    lines = [
        '"""Travel: the eight-process portfolio\'s Domain declarations',
        '(generated by verticals.travel.generator.pack_templates).',
        "",
        "`function` is populated by the same `wire_domain_functions` helper",
        "every other vertical pack uses (from `verticals._helpers`, a",
        "cross-vertical utility, not Travel-specific), cross-validating that",
        "`TRAVEL_FUNCTIONS`'s `owns_domains` rows exactly partition these eight",
        "workflow types with no gaps or overlaps.",
        "",
        "Do not hand-edit -- change the generator template (or",
        "verticals.travel.generator.portfolio) and regenerate via",
        "`uv run python -m verticals.travel.generator`.",
        '"""',
        "from __future__ import annotations",
        "",
        "from api.shared.domain_contracts import Domain, HitlGate, Phase",
        "from verticals._helpers import wire_domain_functions",
        "from verticals.travel.functions import TRAVEL_FUNCTIONS",
        "",
        "_RAW_DOMAINS: dict[str, Domain] = {",
    ]
    for spec in PROCESS_SPECS:
        lines.append(f"    {spec.workflow_type!r}: Domain(")
        lines.append(f"        workflow_type={spec.workflow_type!r},")
        lines.append(f"        display_name={spec.display_name!r},")
        lines.append(f"        workflow_id_prefix={spec.workflow_id_prefix!r},")
        lines.append(f"        orchestrator_name={spec.orchestrator_name!r},")
        lines.append(f"        operator_surface={_operator_surface_for(spec)!r},")
        lines.append("        phases=(")
        for phase in spec.phases:
            lines.append(f"            Phase(name={phase.name!r}, kind={phase.kind!r}),")
        lines.append("        ),")
        if spec.hitl_gate is not None:
            gate = spec.hitl_gate
            lines.append("        hitl_gates=(")
            lines.append("            HitlGate(")
            lines.append(f"                gate_phase={gate.gate_phase!r},")
            lines.append(f"                external_event={gate.external_event!r},")
            lines.append(f"                persona={gate.persona!r},")
            lines.append(f"                wait_probability={gate.wait_probability!r},")
            lines.append("            ),")
            lines.append("        ),")
        else:
            lines.append("        hitl_gates=(),")
        lines.append(f"        skills=({spec.workflow_type!r},),")
        lines.append("        stub=False,")
        lines.append("    ),")
    lines.append("}")
    lines.append("")
    lines.append(
        "TRAVEL_DOMAINS: dict[str, Domain] = wire_domain_functions(_RAW_DOMAINS, dict(TRAVEL_FUNCTIONS))"
    )
    # Render from a sorted tuple, never a bare set/frozenset repr: str hash
    # randomization makes set iteration order vary across interpreter
    # processes, which would make this generated line non-deterministic.
    lines.append(
        "TRAVEL_HERO_WORKFLOW_TYPES: frozenset[str] = frozenset("
        f"{tuple(sorted(HERO_WORKFLOW_TYPES))!r})"
    )
    lines.append("")
    return "\n".join(lines)


