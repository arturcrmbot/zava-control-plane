def render_ui_json() -> str:
    """Render `ui.json`: minimal, valid `VerticalUiManifest` source data.

    `"world"` is a genuine, pre-existing, cross-vertical UI capability name
    (`api.shared.kernel_assets.KNOWN_CAPABILITIES`) -- not Travel
    vocabulary -- declared truthfully because Travel does ship a real,
    non-stub world. Lenses are left empty: none of the small fixed
    `KNOWN_LENSES` set is a genuine fit yet, and no test requires one.
    `world_scene` (Task 8) points at the pack-owned spatial scene
    (`ui/world-scene.json`, rendered by `scene_templates.py`), loaded
    through the shared `api.shared.world_scene_contracts.load_world_scene`
    contract so `/api/runtime` exposes it for this vertical only.
    """
    data = {
        "capabilities": ["world"],
        "lenses": [],
        "theme": {},
        "phase_aliases": {},
        "supplemental_domains": [],
        "aspirational_domains": [],
        "include_meta_skills": False,
        "world_scene": "ui/world-scene.json",
    }
    return json.dumps(data, indent=2, sort_keys=True) + "\n"
