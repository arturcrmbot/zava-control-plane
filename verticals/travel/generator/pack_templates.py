def render_personas_py() -> str:
    """Render `personas.py`: one Persona per authority role (14 total)."""
    process_role_function = {spec.authority_role: spec.function for spec in PROCESS_SPECS}
    process_role_label = {spec.authority_role: spec.display_name for spec in PROCESS_SPECS}
    head_role_function = {
        function_spec.head_role: function_spec.name for function_spec in FUNCTION_SPECS
    }
    head_role_label = {
        function_spec.head_role: function_spec.display for function_spec in FUNCTION_SPECS
    }
    lines = [
        '"""Travel: one Persona per authority role (generated by',
        'verticals.travel.generator.pack_templates).',
        "",
        "Covers all fourteen `TRAVEL_AUTHORITY` roles: the eight process roles",
        "plus their six escalation heads, matching every function's",
        "`persona_hierarchy` in `functions.py`.",
        "",
        "Do not hand-edit -- change the generator template (or",
        "verticals.travel.generator.portfolio) and regenerate via",
        "`uv run python -m verticals.travel.generator`.",
        '"""',
        "from __future__ import annotations",
        "",
        "from api.shared.persona_contracts import Persona",
        "",
        "TRAVEL_PERSONAS: dict[str, Persona] = {",
    ]
    for role, function_name in process_role_function.items():
        lines.append(f"    {role!r}: Persona(")
        lines.append(f"        role={role!r},")
        lines.append('        archetype="approver",')
        lines.append(f"        scope_function={function_name!r},")
        lines.append(f"        workflow_label={process_role_label[role]!r},")
        lines.append("    ),")
    for role, function_name in head_role_function.items():
        lines.append(f"    {role!r}: Persona(")
        lines.append(f"        role={role!r},")
        lines.append('        archetype="approver",')
        lines.append(f"        scope_function={function_name!r},")
        lines.append(f"        workflow_label={head_role_label[role] + ' escalation'!r},")
        lines.append("    ),")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


