def reject(world: "TravelWorld", command: SimulationCommand, reason: str) -> SimulationEvent:
    """Journal an explicit `"command.rejected"` event and return it.

    Never mutates any world record: a rejection is pure evidence that a
    command was refused, and why, on the exact same causal trace as the
    command that was refused.
    """
    return world.runtime.emit(
        "command.rejected",
        actor_id=command.issued_by,
        target_id=None,
        cause_event_id=None,
        trace_id=command.trace_id,
        payload={"command": command.to_dict(), "reason": reason},
    )


def _authority_error(command_type: str, role: str, cost_gbp: float) -> str | None:
    """None if `role` may approve `command_type` at `cost_gbp`, else a reason.

    Every reason names both "authority" and "spend limit" so a caller that
    checks for either phrase (the eight-process contract tests do) always
    finds one.
    """
    authority = TRAVEL_AUTHORITY.get(role)
    if authority is None:
        return f"{role!r} is not a recognised authority role"
    if command_type not in authority.approval_actions:
        return f"{role!r} has no authority to approve {command_type!r}"
    if cost_gbp > authority.spend_limit_gbp:
        return (
            f"{role!r}'s authority spend limit of GBP {authority.spend_limit_gbp:,.2f} "
            f"is exceeded by GBP {cost_gbp:,.2f}"
        )
    return None


def _linked_disruption(world: "TravelWorld", disruption_id: str, resource_id: str) -> Disruption | None:
    """The disruption for `disruption_id` if it exists and names `resource_id`.

    Deliberately ignores `status`: see the module docstring for why a
    disruption already `"resolved"` by an earlier, unrelated command must
    still be accepted as a genuine link here.
    """
    disruption = world.disruptions.get(disruption_id)
    if disruption is None or disruption.resource_id != resource_id:
        return None
    return disruption


def _resolve_disruption(
    world: "TravelWorld", disruption: Disruption, command: SimulationCommand, target_id: str,
) -> SimulationEvent:
    return world._apply(
        "disruption.resolved",
        disruption,
        {"status": "resolved"},
        target_id=target_id,
        trace_id=command.trace_id,
    )


