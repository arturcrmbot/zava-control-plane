def confirm_package_booking(world: "TravelWorld", command: SimulationCommand) -> SimulationEvent:
    payload = command.payload
    quote_id = payload["quote_id"]
    flight_id = payload["flight_id"]
    hotel_id = payload["hotel_id"]
    allotment_id = payload["allotment_id"]
    transfer_id = payload["transfer_id"]
    rooms = int(payload["rooms"])
    role = payload["authorized_by"]

    quote = world.quotes.get(quote_id)
    if quote is None:
        return reject(world, command, f"unknown quote {quote_id!r}")
    if quote.status != "offered":
        return reject(world, command, f"quote {quote_id!r} is {quote.status!r}, not offered")
    if quote.price is None:
        return reject(world, command, f"quote {quote_id!r} has no offered price")
    flight = world.flights.get(flight_id)
    hotel = world.hotels.get(hotel_id)
    allotment = world.allotments.get(allotment_id)
    transfer = world.transfers.get(transfer_id)
    if flight is None or hotel is None or allotment is None or transfer is None:
        return reject(world, command, "unknown flight, hotel, allotment or transfer")

    error = _authority_error(command.type, role, quote.price)
    if error is not None:
        return reject(world, command, error)

    party = world.parties[quote.party_id]
    if flight.reserved + party.size > flight.capacity:
        return reject(world, command, f"flight {flight_id!r} has insufficient capacity")
    if allotment.reserved + rooms > allotment.allotment:
        return reject(world, command, f"allotment {allotment_id!r} has insufficient contracted rooms")
    if transfer.reserved + party.size > transfer.capacity:
        return reject(world, command, f"transfer {transfer_id!r} has insufficient capacity")

    booking_id = f"BKG-{quote_id}"
    events: list[SimulationEvent] = []
    actor_ids: list[str] = [quote.id, flight.id, hotel.id, allotment.id, transfer.id]

    booking = Booking(
        id=booking_id,
        quote_id=quote.id,
        party_id=quote.party_id,
        customer_id=quote.customer_id,
        flight_id=flight_id,
        hotel_id=hotel_id,
        allotment_id=allotment_id,
        transfer_id=transfer_id,
        rooms=rooms,
        total_price=quote.price,
        status="confirmed",
    )
    world.bookings[booking.id] = booking
    events.append(
        world._created(
            "booking.confirmed", booking, target_id=quote.id, trace_id=command.trace_id,
            extra_payload={"party_id": quote.party_id, "flight_id": flight_id},
        )
    )
    actor_ids.append(booking.id)

    events.append(
        world._apply(
            "quote.converted", quote, {"status": "converted"}, target_id=booking.id,
            trace_id=command.trace_id,
        )
    )
    events.append(
        world._apply(
            "flight.capacity_reserved", flight, {"reserved": flight.reserved + party.size},
            target_id=booking.id, trace_id=command.trace_id,
        )
    )
    events.append(
        world._apply(
            "hotel.rooms_reserved", allotment, {"reserved": allotment.reserved + rooms},
            target_id=booking.id, trace_id=command.trace_id,
        )
    )
    events.append(
        world._apply(
            "transfer.capacity_reserved", transfer, {"reserved": transfer.reserved + party.size},
            target_id=booking.id, trace_id=command.trace_id,
        )
    )

    payment = Payment(id=f"PAY-{booking_id}", booking_id=booking.id, kind="full", amount=quote.price)
    world.payments[payment.id] = payment
    events.append(
        world._created(
            "payment.succeeded", payment, target_id=booking.id, trace_id=command.trace_id,
        )
    )
    actor_ids.append(payment.id)

    result = world._apply(
        "booking.paid",
        booking,
        {"status": "paid"},
        target_id=quote.id,
        trace_id=command.trace_id,
        extra_payload={
            "affected_actor_ids": actor_ids,
            "evidence_event_ids": [event.event_id for event in events],
        },
    )
    return result


