_REFUND_RATE = 0.9  # customer keeps 90% back; a 10% cancellation fee is retained.


def cancel_and_refund_booking(world: "TravelWorld", command: SimulationCommand) -> SimulationEvent:
    payload = command.payload
    disruption_id = payload["disruption_id"]
    booking_id = payload["booking_id"]
    role = payload["authorized_by"]

    booking = world.bookings.get(booking_id)
    if booking is None:
        return reject(world, command, f"unknown booking {booking_id!r}")
    if booking.status == "cancelled":
        # Fail-closed terminal-state guard: a booking already cancelled --
        # whether by an earlier, distinct cancel_and_refund_booking command
        # or by any other legitimate handler that terminates a booking (for
        # example resolve_payment_exception's "release" action) -- must
        # never be cancelled or refunded again. This check runs before any
        # mutation and before world.apply_command's command_id cache is
        # even consulted for a *different* id, so a genuinely distinct
        # command_id naming this same, already-cancelled booking is
        # rejected here instead of re-releasing capacity or re-issuing a
        # refund. A replay of the *same* command_id never reaches this
        # function at all -- it is served from that cache first -- so this
        # guard never disturbs that idempotent replay behaviour.
        return reject(world, command, f"booking {booking_id!r} is already cancelled")
    disruption = _linked_disruption(world, disruption_id, booking_id)
    if disruption is None:
        return reject(
            world, command,
            f"no reported customer_cancellation_accepted disruption links {disruption_id!r} to booking "
            f"{booking_id!r}",
        )

    refund_amount = booking.total_price * _REFUND_RATE
    error = _authority_error(command.type, role, refund_amount)
    if error is not None:
        return reject(world, command, error)

    party = world.parties[booking.party_id]
    flight = world.flights[booking.flight_id]
    allotment = world.allotments[booking.allotment_id]
    transfer = world.transfers[booking.transfer_id]

    events = [
        world._apply(
            "flight.capacity_released", flight, {"reserved": flight.reserved - party.size},
            target_id=booking.id, trace_id=command.trace_id,
        ),
        world._apply(
            "hotel.rooms_released", allotment, {"reserved": allotment.reserved - booking.rooms},
            target_id=booking.id, trace_id=command.trace_id,
        ),
        world._apply(
            "transfer.capacity_released", transfer, {"reserved": transfer.reserved - party.size},
            target_id=booking.id, trace_id=command.trace_id,
        ),
        world._apply(
            "booking.cancelled", booking, {"status": "cancelled"}, target_id=disruption.id,
            trace_id=command.trace_id,
        ),
        _resolve_disruption(world, disruption, command, booking.id),
    ]

    refund = Refund(
        id=f"REF-{booking_id}", booking_id=booking_id, amount=refund_amount,
        reason="customer_cancellation_accepted", status="issued",
    )
    world.refunds[refund.id] = refund
    result = world._created(
        "refund.issued",
        refund,
        target_id=booking.id,
        trace_id=command.trace_id,
        extra_payload={
            "affected_actor_ids": [
                booking.id, flight.id, allotment.id, transfer.id, disruption.id, refund.id,
            ],
            "evidence_event_ids": [event.event_id for event in events],
        },
    )
    return result


