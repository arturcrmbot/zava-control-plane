# ---------------------------------------------------------------------------


def adjust_package_allotment(world: "TravelWorld", command: SimulationCommand) -> SimulationEvent:
    payload = command.payload
    from_id = payload["from_allotment_id"]
    to_id = payload["to_allotment_id"]
    rooms = int(payload["rooms"])
    value_gbp = float(payload["estimated_value_gbp"])
    role = payload["authorized_by"]

    donor = world.allotments.get(from_id)
    recipient = world.allotments.get(to_id)
    if donor is None or recipient is None:
        return reject(world, command, "unknown donor or recipient allotment")

    error = _authority_error(command.type, role, value_gbp)
    if error is not None:
        return reject(world, command, error)

    if rooms > donor.allotment - donor.reserved:
        return reject(world, command, f"allotment {from_id!r} lacks {rooms} rooms of donor headroom")
    recipient_headroom = recipient.total - recipient.allotment
    if rooms > recipient_headroom:
        return reject(world, command, f"allotment {to_id!r} would breach its contracted total")

    events = [
        world._apply(
            "hotel.allotment_reduced", donor, {"allotment": donor.allotment - rooms},
            target_id=to_id, trace_id=command.trace_id,
        ),
    ]
    result = world._apply(
        "hotel.allotment_adjusted",
        recipient,
        {"allotment": recipient.allotment + rooms},
        target_id=from_id,
        trace_id=command.trace_id,
        extra_payload={
            "affected_actor_ids": [donor.id, recipient.id],
            "evidence_event_ids": [event.event_id for event in events],
            "rooms": rooms,
        },
    )
    return result


