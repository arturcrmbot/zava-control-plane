def reaccommodate_travellers(world: "TravelWorld", command: SimulationCommand) -> SimulationEvent:
    """Dispatch by payload shape -- never by any out-of-band flag.

    Task 6's real `TravelFlightDisruptionRecoveryOrchestrator` (via its
    `TravelRecoveryBuildCommand` activity) only ever issues a payload
    carrying `"option_id"` -- the bounded, ranked `RecoveryOption` it
    built the command from -- routed to
    `_reaccommodate_travellers_from_option`. Every other payload is the
    original, hand-issued
    (booking_id/disruption_id/to_flight_id/to_transfer_id/
    estimated_cost_gbp/authorized_by) shape from Task 4/5, preserved
    byte-identical as `_reaccommodate_travellers_legacy` so its three
    existing contract tests keep passing unchanged.
    """
    if "option_id" in command.payload:
        return _reaccommodate_travellers_from_option(world, command)
    return _reaccommodate_travellers_legacy(world, command)


def _reaccommodate_travellers_legacy(world: "TravelWorld", command: SimulationCommand) -> SimulationEvent:
    payload = command.payload
    booking_id = payload["booking_id"]
    disruption_id = payload["disruption_id"]
    to_flight_id = payload["to_flight_id"]
    to_transfer_id = payload["to_transfer_id"]
    cost_gbp = float(payload["estimated_cost_gbp"])
    role = payload["authorized_by"]

    booking = world.bookings.get(booking_id)
    if booking is None:
        return reject(world, command, f"unknown booking {booking_id!r}")
    disruption = _linked_disruption(world, disruption_id, booking.flight_id)
    if disruption is None:
        return reject(
            world, command,
            f"no reported flight_cancellation disruption links {disruption_id!r} to booking "
            f"{booking_id!r}'s flight",
        )
    to_flight = world.flights.get(to_flight_id)
    to_transfer = world.transfers.get(to_transfer_id)
    if to_flight is None or to_transfer is None:
        return reject(world, command, "unknown replacement flight or transfer")

    error = _authority_error(command.type, role, cost_gbp)
    if error is not None:
        return reject(world, command, error)

    party = world.parties[booking.party_id]
    if to_flight.reserved + party.size > to_flight.capacity:
        return reject(world, command, f"flight {to_flight_id!r} has insufficient capacity")
    if to_transfer.reserved + party.size > to_transfer.capacity:
        return reject(world, command, f"transfer {to_transfer_id!r} has insufficient capacity")

    from_flight = world.flights[booking.flight_id]
    from_transfer = world.transfers[booking.transfer_id]

    events = [
        world._apply(
            "flight.capacity_released", from_flight, {"reserved": from_flight.reserved - party.size},
            target_id=booking.id, trace_id=command.trace_id,
        ),
        world._apply(
            "flight.capacity_reserved", to_flight, {"reserved": to_flight.reserved + party.size},
            target_id=booking.id, trace_id=command.trace_id,
        ),
        world._apply(
            "transfer.capacity_released", from_transfer, {"reserved": from_transfer.reserved - party.size},
            target_id=booking.id, trace_id=command.trace_id,
        ),
        world._apply(
            "transfer.capacity_reserved", to_transfer, {"reserved": to_transfer.reserved + party.size},
            target_id=booking.id, trace_id=command.trace_id,
        ),
        _resolve_disruption(world, disruption, command, booking.id),
    ]

    result = world._apply(
        "booking.reaccommodated",
        booking,
        {"flight_id": to_flight_id, "transfer_id": to_transfer_id},
        target_id=disruption.id,
        trace_id=command.trace_id,
        extra_payload={
            "affected_actor_ids": [
                booking.id, from_flight.id, to_flight.id, from_transfer.id, to_transfer.id, disruption.id,
            ],
            "evidence_event_ids": [event.event_id for event in events],
        },
    )
    return result


def _reaccommodate_travellers_from_option(world: "TravelWorld", command: SimulationCommand) -> SimulationEvent:
    """Task 6: apply the one typed `reaccommodate_travellers` command a real
    `TravelFlightDisruptionRecoveryOrchestrator` instance built from its own
    bounded, ranked `RecoveryOption` -- after valid `head_of_operations`
    approval or bounded `operations_controller` auto-authority -- as one
    atomic mutation.

    Validates every actor id, that the old flight is genuinely cancelled,
    that this exact booking is still eligible (never already moved off it
    -- so a distinct re-entry against an already-reaccommodated booking
    always rejects), that the replacement flight/transfer are operational
    with real spare capacity for the whole party, that the destination and
    hotel/allotment stay exactly what the option promised, that the old
    and new supplier ids the option carries still name the real operating
    supplier of the corresponding flight (never a stale or tampered
    supplier identity), that the option's own capacity/cost evidence still
    matches live world state (never a stale option), and that the embedded
    decision actually carries enough authority for this option's own
    bound/materiality -- all before touching a single record. Every step
    from here on is a pure, in-memory dataclass mutation that cannot
    itself fail once validation has passed, so no compensation logic is
    needed or implemented.
    """
    payload = command.payload
    option_id = payload.get("option_id")
    disruption_id = payload.get("disruption_id")
    booking_id = payload.get("booking_id")
    party_id = payload.get("party_id")
    old_flight_id = payload.get("old_flight_id")
    new_flight_id = payload.get("new_flight_id")
    old_supplier_id = payload.get("old_supplier_id")
    new_supplier_id = payload.get("new_supplier_id")
    old_transfer_id = payload.get("old_transfer_id")
    new_transfer_id = payload.get("new_transfer_id")
    hotel_id = payload.get("hotel_id")
    allotment_id = payload.get("allotment_id")
    workflow_id = payload.get("workflow_id")
    decision_outcome = payload.get("decision_outcome")
    decided_by = payload.get("decided_by")
    incremental_cost_gbp = payload.get("incremental_cost_gbp")
    material_changes = payload.get("material_changes") or []
    capacity_evidence = payload.get("capacity_evidence") or {}

    booking = world.bookings.get(booking_id)
    party = world.parties.get(party_id)
    old_flight = world.flights.get(old_flight_id)
    new_flight = world.flights.get(new_flight_id)
    old_transfer = world.transfers.get(old_transfer_id)
    new_transfer = world.transfers.get(new_transfer_id)
    hotel = world.hotels.get(hotel_id)
    allotment = world.allotments.get(allotment_id)
    missing = [
        name
        for name, record in (
            ("booking_id", booking),
            ("party_id", party),
            ("old_flight_id", old_flight),
            ("new_flight_id", new_flight),
            ("old_transfer_id", old_transfer),
            ("new_transfer_id", new_transfer),
            ("hotel_id", hotel),
            ("allotment_id", allotment),
        )
        if record is None
    ]
    if missing:
        return reject(world, command, f"unknown actor id(s) for: {', '.join(missing)}")

    if booking.party_id != party_id:
        return reject(world, command, f"party {party_id!r} is not booking {booking_id!r}'s own party")

    disruption = _linked_disruption(world, disruption_id, old_flight_id)
    if disruption is None:
        return reject(
            world, command,
            f"no reported flight_cancellation disruption links {disruption_id!r} to flight {old_flight_id!r}",
        )
    if old_flight.status != "cancelled":
        return reject(world, command, f"flight {old_flight_id!r} is not cancelled")
    if booking.status == "cancelled":
        return reject(world, command, f"booking {booking_id!r} is cancelled")
    if booking.flight_id != old_flight_id:
        return reject(
            world, command,
            f"booking {booking_id!r} is no longer on flight {old_flight_id!r} "
            "(already reaccommodated, or never booked on it)",
        )
    if new_flight.status != "scheduled":
        return reject(world, command, f"replacement flight {new_flight_id!r} is not operational")
    # This world has no separate calendar-date concept beyond destination and
    # scheduled arrival minute (already scored as arrival_delay_minutes by
    # the planner); "compatible destination/date bounds" is enforced here as
    # an exact destination match.
    if new_flight.destination_id != old_flight.destination_id:
        return reject(world, command, "replacement flight changes destination -- unsupported by this handler")
    # Independently re-validate supplier identity against the actual flight
    # records rather than trusting the option's own carried evidence: a
    # command whose old/new supplier no longer names the real operating
    # supplier of the corresponding flight is stale or tampered evidence,
    # and must be rejected before any mutation, exactly like stale
    # capacity/cost evidence below.
    if old_supplier_id != old_flight.supplier_id:
        return reject(
            world, command,
            f"option {option_id!r} is stale: old_supplier_id {old_supplier_id!r} does not match "
            f"flight {old_flight_id!r}'s real supplier {old_flight.supplier_id!r}",
        )
    if new_supplier_id != new_flight.supplier_id:
        return reject(
            world, command,
            f"option {option_id!r} is stale: new_supplier_id {new_supplier_id!r} does not match "
            f"flight {new_flight_id!r}'s real supplier {new_flight.supplier_id!r}",
        )
    if new_transfer.flight_id != new_flight_id:
        return reject(world, command, f"transfer {new_transfer_id!r} is not paired with flight {new_flight_id!r}")
    if hotel_id != booking.hotel_id or allotment_id != booking.allotment_id:
        return reject(world, command, "replacement option changes hotel/allotment -- unsupported by this handler")

    if new_flight.reserved != capacity_evidence.get("new_flight_reserved"):
        return reject(
            world, command, f"option {option_id!r} is stale: flight {new_flight_id!r} capacity has moved on"
        )
    if new_transfer.reserved != capacity_evidence.get("new_transfer_reserved"):
        return reject(
            world, command, f"option {option_id!r} is stale: transfer {new_transfer_id!r} capacity has moved on"
        )
    if incremental_cost_gbp is None or float(incremental_cost_gbp) != new_flight.base_fare_gbp:
        return reject(
            world, command,
            f"option {option_id!r} is stale: incremental cost no longer matches flight {new_flight_id!r}",
        )

    if new_flight.reserved + party.size > new_flight.capacity:
        return reject(world, command, f"flight {new_flight_id!r} has insufficient capacity")
    if new_transfer.reserved + party.size > new_transfer.capacity:
        return reject(world, command, f"transfer {new_transfer_id!r} has insufficient capacity")

    requires_approval = float(incremental_cost_gbp) > _RECOVERY_AUTO_APPROVE_BOUND_GBP or bool(material_changes)
    if requires_approval:
        if decision_outcome != "approved" or decided_by != "head_of_operations":
            return reject(
                world, command,
                f"option {option_id!r} requires head_of_operations approval (incremental cost GBP "
                f"{float(incremental_cost_gbp):,.2f}, material_changes={list(material_changes)!r}); "
                f"decision was {decision_outcome!r} by {decided_by!r}",
            )
    elif decision_outcome not in ("approved", "auto_approved"):
        return reject(world, command, f"option {option_id!r} carries no valid approval or auto-authority")

    from_flight, to_flight = old_flight, new_flight
    from_transfer, to_transfer = old_transfer, new_transfer

    events = [
        world._apply(
            "flight.capacity_released", from_flight, {"reserved": from_flight.reserved - party.size},
            target_id=booking.id, trace_id=command.trace_id,
        ),
        world._apply(
            "flight.capacity_reserved", to_flight, {"reserved": to_flight.reserved + party.size},
            target_id=booking.id, trace_id=command.trace_id,
        ),
        world._apply(
            "transfer.capacity_released", from_transfer, {"reserved": from_transfer.reserved - party.size},
            target_id=booking.id, trace_id=command.trace_id,
        ),
        world._apply(
            "transfer.capacity_reserved", to_transfer, {"reserved": to_transfer.reserved + party.size},
            target_id=booking.id, trace_id=command.trace_id,
        ),
        _resolve_disruption(world, disruption, command, booking.id),
        world._apply(
            "party.reaccommodated", party, {"state": "reaccommodated"},
            target_id=booking.id, trace_id=command.trace_id,
        ),
    ]

    # Read the same id `TravelRecoveryBuildCommand` already minted for this
    # decision rather than recomputing the formula a second time here, so
    # the two can never silently drift apart; a hand-built command missing
    # it (never produced by the real orchestrator) falls back to the same
    # deterministic formula.
    decision_id = payload.get("decision_id") or f"DEC-{workflow_id}-{option_id}"
    recovery_decision = RecoveryDecision(
        id=decision_id, workflow_id=workflow_id, option_id=option_id,
        outcome=decision_outcome, decided_by=decided_by,
    )
    world.recovery_decisions[decision_id] = recovery_decision
    events.append(
        world._created(
            "recovery.decision_recorded", recovery_decision,
            target_id=booking.id, trace_id=command.trace_id,
            extra_payload={"outcome": decision_outcome, "decided_by": decided_by, "option_id": option_id},
        )
    )

    recovery_command = RecoveryCommand(
        id=command.command_id, workflow_id=workflow_id, decision_id=decision_id, option_id=option_id,
        booking_id=booking.id, party_id=party.id, old_flight_id=old_flight_id, new_flight_id=new_flight_id,
        old_supplier_id=old_supplier_id, new_supplier_id=new_supplier_id,
        incremental_cost_gbp=float(incremental_cost_gbp),
    )
    world.recovery_commands[recovery_command.id] = recovery_command
    events.append(
        world._created(
            "recovery.command_recorded", recovery_command,
            target_id=booking.id, trace_id=command.trace_id,
            extra_payload={
                "decision_id": decision_id, "option_id": option_id,
                "old_flight_id": old_flight_id, "new_flight_id": new_flight_id,
                "old_supplier_id": old_supplier_id, "new_supplier_id": new_supplier_id,
            },
        )
    )

    result = world._apply(
        "booking.reaccommodated",
        booking,
        {"flight_id": new_flight_id, "transfer_id": new_transfer_id, "recovery_status": "reaccommodated"},
        target_id=disruption.id,
        trace_id=command.trace_id,
        extra_payload={
            "affected_actor_ids": [
                booking.id, party.id, from_flight.id, to_flight.id, from_transfer.id, to_transfer.id, disruption.id,
                old_supplier_id, new_supplier_id,
            ],
            "evidence_event_ids": [event.event_id for event in events],
            "option_id": option_id,
            "decision_id": decision_id,
            "command_id": recovery_command.id,
            "workflow_id": workflow_id,
        },
    )

    # Real, computed verification -- not a hardcoded "pass" -- of exactly
    # the invariant Task 6 requires: the booking/party now genuinely point
    # at the recovered itinerary and capacity conservation holds either
    # side of the move.
    conservation_holds = (
        booking.flight_id == new_flight_id
        and booking.transfer_id == new_transfer_id
        and booking.recovery_status == "reaccommodated"
        and party.state == "reaccommodated"
        and 0 <= to_flight.reserved <= to_flight.capacity
        and 0 <= to_transfer.reserved <= to_transfer.capacity
        and 0 <= from_flight.reserved
        and 0 <= from_transfer.reserved
    )
    evaluation_id = f"EVAL-{workflow_id}-{option_id}"
    recovery_evaluation = RecoveryEvaluation(
        id=evaluation_id, workflow_id=workflow_id, command_id=recovery_command.id,
        booking_id=booking.id, party_id=party.id, status="pass" if conservation_holds else "fail",
    )
    world.recovery_evaluations[evaluation_id] = recovery_evaluation
    world._created(
        "recovery.evaluation_recorded", recovery_evaluation,
        target_id=booking.id, trace_id=command.trace_id, cause_event_id=result.event_id,
        extra_payload={"status": recovery_evaluation.status, "command_id": recovery_command.id},
    )

    return result


