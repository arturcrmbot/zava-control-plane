def dispatch_replacement_transfer(world: "TravelWorld", command: SimulationCommand) -> SimulationEvent:
    payload = command.payload
    disruption_id = payload["disruption_id"]
    transfer_id = payload["transfer_id"]
    cost_gbp = float(payload["estimated_cost_gbp"])
    role = payload["authorized_by"]

    disruption = _linked_disruption(world, disruption_id, transfer_id)
    if disruption is None:
        return reject(
            world, command,
            f"no reported transfer_arrival_risk disruption links {disruption_id!r} to transfer "
            f"{transfer_id!r}",
        )
    transfer = world.transfers.get(transfer_id)
    if transfer is None:
        return reject(world, command, f"unknown transfer {transfer_id!r}")

    error = _authority_error(command.type, role, cost_gbp)
    if error is not None:
        return reject(world, command, error)

    replacement_id = f"TRF-REPL-{transfer_id}"
    events: list[SimulationEvent] = []
    if replacement_id not in world.transfers:
        replacement = Transfer(
            id=replacement_id,
            destination_id=transfer.destination_id,
            flight_id=transfer.flight_id,
            supplier_id=transfer.supplier_id,
            capacity=transfer.capacity,
            reserved=transfer.reserved,
            status="scheduled",
        )
        world.transfers[replacement.id] = replacement
        events.append(
            world._created(
                "transfer.replacement_created", replacement, target_id=transfer_id,
                trace_id=command.trace_id,
            )
        )
    else:
        replacement = world.transfers[replacement_id]

    events.append(
        world._apply(
            "transfer.superseded", transfer, {"status": "superseded"}, target_id=replacement.id,
            trace_id=command.trace_id,
        )
    )
    events.append(_resolve_disruption(world, disruption, command, replacement.id))

    rebound_ids: list[str] = []
    for booking in sorted(world.bookings.values(), key=lambda booking: booking.id):
        if booking.transfer_id != transfer_id:
            continue
        events.append(
            world._apply(
                "booking.transfer_rebound", booking, {"transfer_id": replacement.id},
                target_id=replacement.id, trace_id=command.trace_id,
            )
        )
        rebound_ids.append(booking.id)

    result = world._apply(
        "transfer.replacement_dispatched",
        replacement,
        {},
        target_id=transfer.id,
        trace_id=command.trace_id,
        extra_payload={
            "affected_actor_ids": [transfer.id, replacement.id, disruption.id, *rebound_ids],
            "evidence_event_ids": [event.event_id for event in events],
            "rebound_booking_ids": rebound_ids,
        },
    )
    return result


