def resolve_payment_exception(world: "TravelWorld", command: SimulationCommand) -> SimulationEvent:
    payload = command.payload
    disruption_id = payload["disruption_id"]
    booking_id = payload["booking_id"]
    action = payload["action"]
    role = payload["authorized_by"]

    booking = world.bookings.get(booking_id)
    if booking is None:
        return reject(world, command, f"unknown booking {booking_id!r}")
    disruption = _linked_disruption(world, disruption_id, booking_id)
    if disruption is None:
        return reject(
            world, command,
            f"no reported balance_payment_exception disruption links {disruption_id!r} to booking "
            f"{booking_id!r}",
        )
    if action not in ("retry", "release"):
        return reject(world, command, f"unknown resolution action {action!r}")

    error = _authority_error(command.type, role, 0.0)
    if error is not None:
        return reject(world, command, error)

    events = [_resolve_disruption(world, disruption, command, booking.id)]

    if action == "retry":
        remaining = booking.total_price - sum(
            payment.amount for payment in world.payments.values() if payment.booking_id == booking_id
        )
        events.append(
            world._apply(
                "booking.paid",
                booking,
                {"status": "paid"},
                target_id=disruption.id,
                trace_id=command.trace_id,
            )
        )
        payment = Payment(
            id=f"PAY-RETRY-{booking_id}", booking_id=booking_id, kind="balance", amount=remaining,
        )
        world.payments[payment.id] = payment
        result = world._created(
            "payment.succeeded",
            payment,
            target_id=disruption.id,
            trace_id=command.trace_id,
            extra_payload={
                "affected_actor_ids": [booking.id, disruption.id, payment.id],
                "evidence_event_ids": [event.event_id for event in events],
            },
        )
        return result

    # action == "release": free the booking's inventory instead of retrying
    # payment. Idempotent-safe against a booking an earlier, unrelated
    # command already cancelled (see the module docstring): only release
    # capacity when the booking is not already cancelled, so a booking's
    # reserved counts are never released twice.
    already_cancelled = booking.status == "cancelled"
    if not already_cancelled:
        party = world.parties[booking.party_id]
        flight = world.flights[booking.flight_id]
        events.append(
            world._apply(
                "flight.capacity_released", flight, {"reserved": flight.reserved - party.size},
                target_id=disruption.id, trace_id=command.trace_id,
            )
        )
        allotment = world.allotments[booking.allotment_id]
        events.append(
            world._apply(
                "hotel.rooms_released", allotment, {"reserved": allotment.reserved - booking.rooms},
                target_id=disruption.id, trace_id=command.trace_id,
            )
        )
        transfer = world.transfers[booking.transfer_id]
        events.append(
            world._apply(
                "transfer.capacity_released", transfer, {"reserved": transfer.reserved - party.size},
                target_id=disruption.id, trace_id=command.trace_id,
            )
        )
        result = world._apply(
            "booking.cancelled",
            booking,
            {"status": "cancelled"},
            target_id=disruption.id,
            trace_id=command.trace_id,
            extra_payload={
                "affected_actor_ids": [booking.id, disruption.id],
                "evidence_event_ids": [event.event_id for event in events],
            },
        )
        return result

    # Already cancelled by an earlier command against the same booking:
    # journal that this resolution observed and accepted that fact, without
    # releasing already-released capacity a second time.
    result = world._apply(
        "booking.cancelled",
        booking,
        {},
        target_id=disruption.id,
        trace_id=command.trace_id,
        extra_payload={
            "already_cancelled": True,
            "affected_actor_ids": [booking.id, disruption.id],
            "evidence_event_ids": [event.event_id for event in events],
        },
    )
    return result


