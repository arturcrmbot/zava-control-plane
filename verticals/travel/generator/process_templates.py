def _detect_disruption_kind(world: Any, *, kind: str, event_type: str) -> list[SimulationEvent]:
    """Journal one real sensor event per reported-but-unresolved `kind` disruption.

    Shared by five of the six disruption-driven detectors below -- every one
    except `detect_flight_cancellation_impact`, which needs its own
    eligibility-gated, rising-edge logic (see below): a disruption only
    ever trips its sensor while genuinely `"reported"`, so a disruption an
    earlier command already resolved never re-trips it.
    """
    events: list[SimulationEvent] = []
    for disruption in sorted(world.disruptions.values(), key=lambda d: d.id):
        if disruption.kind != kind or disruption.status != "reported":
            continue
        events.append(
            world.runtime.emit(
                event_type,
                target_id=disruption.resource_id,
                payload={"disruption_id": disruption.id, "measurements": {"kind": kind}},
            )
        )
    return events


def detect_quote_ready(world: Any) -> list[SimulationEvent]:
    """Real sensor: every currently-offered quote is ready to be confirmed."""
    events: list[SimulationEvent] = []
    for quote in sorted(world.quotes.values(), key=lambda quote: quote.id):
        if quote.status != "offered":
            continue
        events.append(
            world.runtime.emit(
                "sensor.quote_ready_tripped",
                target_id=quote.id,
                payload={"quote_id": quote.id, "measurements": {"price": quote.price}},
            )
        )
    return events


def detect_capacity_pressure(world: Any, threshold: float = 0.02) -> list[SimulationEvent]:
    """Real sensor: an allotment's reserved/contracted ratio at or above `threshold`."""
    events: list[SimulationEvent] = []
    for allotment in sorted(world.allotments.values(), key=lambda allotment: allotment.id):
        if allotment.allotment <= 0:
            continue
        ratio = allotment.reserved / allotment.allotment
        if ratio < threshold:
            continue
        events.append(
            world.runtime.emit(
                "sensor.capacity_pressure_tripped",
                target_id=allotment.id,
                payload={"allotment_id": allotment.id, "measurements": {"ratio": ratio}},
            )
        )
    return events


_SENSOR_FLIGHT_CANCELLATION_IMPACT = "sensor:flight_cancellation_impact"
_ELIGIBLE_BOOKING_STATUSES = frozenset({"confirmed", "deposit_paid", "paid"})


def detect_flight_cancellation_impact(world: Any) -> list[SimulationEvent]:
    """Real, state-derived sensor for a reported flight-cancellation disruption
    whose flight still has at least one affected paid/confirmed booking and
    traveller party.

    Bespoke rather than delegated to `_detect_disruption_kind` (unlike the
    other six disruption-driven detectors): a cancellation against a flight
    with no eligible demand never trips this sensor at all -- the condition
    is read from real world state, never faked. Once a disruption has
    tripped this sensor, this function never re-emits `"sensor.tripped"`
    for it again: calling it again (or advancing the simulation further)
    while the same condition remains true is always a safe, idempotent
    no-op, since the rising edge is re-derived from the journal itself on
    every call rather than from any separate latch.
    """
    already_tripped = {
        event.payload.get("disruption_id")
        for event in world.runtime.journal
        if event.type == "sensor.tripped" and event.payload.get("sensor_id") == _SENSOR_FLIGHT_CANCELLATION_IMPACT
    }
    events_by_id = {event.event_id: event for event in world.runtime.journal}

    events: list[SimulationEvent] = []
    for disruption in sorted(world.disruptions.values(), key=lambda d: d.id):
        if disruption.kind != "flight_cancellation" or disruption.status != "reported":
            continue
        if disruption.id in already_tripped:
            continue

        flight_id = disruption.resource_id
        affected_bookings = sorted(
            (
                booking
                for booking in world.bookings.values()
                if booking.flight_id == flight_id and booking.status in _ELIGIBLE_BOOKING_STATUSES
            ),
            key=lambda booking: booking.id,
        )
        if not affected_bookings:
            continue

        party_ids = sorted({booking.party_id for booking in affected_bookings})
        parties = [world.parties[party_id] for party_id in party_ids]
        member_customer_ids = sorted(
            {customer_id for party in parties for customer_id in party.member_customer_ids}
        )
        hotel_ids = sorted({booking.hotel_id for booking in affected_bookings})
        transfer_ids = sorted({booking.transfer_id for booking in affected_bookings})
        flight = world.flights[flight_id]
        supplier_ids = sorted(
            {flight.supplier_id}
            | {world.hotels[hotel_id].supplier_id for hotel_id in hotel_ids}
            | {world.transfers[transfer_id].supplier_id for transfer_id in transfer_ids}
        )
        traveller_count = sum(party.size for party in parties)
        actor_ids = sorted(
            {flight_id, disruption.id, *(b.id for b in affected_bookings), *party_ids}
            | set(member_customer_ids)
            | set(hotel_ids)
            | set(transfer_ids)
            | set(supplier_ids)
        )

        cause_event = events_by_id[disruption.last_event_id]
        events.append(
            world.runtime.emit(
                "sensor.tripped",
                actor_id=disruption.id,
                target_id=flight_id,
                cause_event_id=cause_event.event_id,
                trace_id=cause_event.trace_id,
                payload={
                    "sensor_id": _SENSOR_FLIGHT_CANCELLATION_IMPACT,
                    "disruption_id": disruption.id,
                    "flight_id": flight_id,
                    "booking_ids": [booking.id for booking in affected_bookings],
                    "party_ids": party_ids,
                    "member_customer_ids": member_customer_ids,
                    "hotel_ids": hotel_ids,
                    "transfer_ids": transfer_ids,
                    "supplier_ids": supplier_ids,
                    "actor_ids": actor_ids,
                    "measurements": {
                        "affected_booking_count": len(affected_bookings),
                        "affected_party_count": len(party_ids),
                        "affected_traveller_count": traveller_count,
                        "seats_impacted": traveller_count,
                        "material_change": True,
                    },
                },
            )
        )
    return events


