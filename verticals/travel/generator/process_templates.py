def _run_setup(world: Any, *, run_until_minutes: float, disruption: tuple[str, str] | None) -> None:
    world.run(run_until_minutes)
    if disruption is not None:
        kind, resource_id = disruption
        world.report_disruption(kind=kind, resource_id=resource_id)


def _run_detect(world: Any, *, workflow_type: str, target_id: str) -> SimulationEvent:
    events = DETECTORS[workflow_type](world)
    return next(event for event in events if event.target_id == target_id)


@dataclass(frozen=True)
class ReferenceCase:
    """One real, executable reference scenario for one portfolio process."""

    workflow_type: str
    role: str
    run_until_minutes: float
    disruption: tuple[str, str] | None
    detect_target_id: str
    command_id: str
    command_type: str
    command_payload: dict[str, Any]

    def setup(self, world: Any) -> None:
        _run_setup(world, run_until_minutes=self.run_until_minutes, disruption=self.disruption)

    def detect(self, world: Any) -> SimulationEvent:
        return _run_detect(world, workflow_type=self.workflow_type, target_id=self.detect_target_id)

    def build_command(self, world: Any, objective: Any) -> SimulationCommand:
        return SimulationCommand(
            command_id=self.command_id,
            trace_id=objective.trace_id,
            issued_by=objective.claimed_by,
            type=self.command_type,
            payload=dict(self.command_payload),
        )

