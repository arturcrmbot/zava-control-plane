def evaluate_booking_confirmed_and_paid(world: Any, *, booking_id: str) -> dict[str, Any]:
    """Pass iff `booking_id` names a real booking whose status is `"paid"`."""
    booking = world.bookings.get(booking_id)
    if booking is None:
        return {"status": "fail", "booking_id": booking_id, "reason": "unknown booking"}
    if booking.status != "paid":
        return {"status": "fail", "booking_id": booking_id, "reason": f"booking is {booking.status!r}"}
    return {"status": "pass", "booking_id": booking_id, "total_price": booking.total_price}


def evaluate_capacity_within_bounds(world: Any, *, allotment_id: str) -> dict[str, Any]:
    """Pass iff `allotment_id`'s conservation invariant holds and it is not over-pressured."""
    allotment = world.allotments.get(allotment_id)
    if allotment is None:
        return {"status": "fail", "allotment_id": allotment_id, "reason": "unknown allotment"}
    conserved = 0 <= allotment.occupied <= allotment.reserved <= allotment.allotment <= allotment.total
    if not conserved:
        return {"status": "fail", "allotment_id": allotment_id, "reason": "conservation invariant broken"}
    ratio = (allotment.reserved / allotment.allotment) if allotment.allotment else 0.0
    return {"status": "pass", "allotment_id": allotment_id, "ratio": ratio}


def evaluate_travellers_reaccommodated(world: Any, *, booking_id: str, disruption_id: str) -> dict[str, Any]:
    """Pass iff `booking_id` exists and its linked disruption is `"resolved"`."""
    booking = world.bookings.get(booking_id)
    disruption = world.disruptions.get(disruption_id)
    if booking is None or disruption is None:
        return {"status": "fail", "booking_id": booking_id, "reason": "unknown booking or disruption"}
    if disruption.status != "resolved":
        return {"status": "fail", "booking_id": booking_id, "reason": "disruption not yet resolved"}
    return {"status": "pass", "booking_id": booking_id, "flight_id": booking.flight_id}


def evaluate_accommodation_restored(world: Any, *, disruption_id: str) -> dict[str, Any]:
    """Pass iff the named hotel-shortfall disruption is `"resolved"`."""
    disruption = world.disruptions.get(disruption_id)
    if disruption is None:
        return {"status": "fail", "disruption_id": disruption_id, "reason": "unknown disruption"}
    if disruption.status != "resolved":
        return {"status": "fail", "disruption_id": disruption_id, "reason": "not yet resolved"}
    return {"status": "pass", "disruption_id": disruption_id}


def evaluate_refund_settled(world: Any, *, booking_id: str) -> dict[str, Any]:
    """Pass iff `booking_id` is cancelled and carries exactly one issued refund."""
    booking = world.bookings.get(booking_id)
    if booking is None or booking.status != "cancelled":
        return {"status": "fail", "booking_id": booking_id, "reason": "booking not cancelled"}
    refunds = [refund for refund in world.refunds.values() if refund.booking_id == booking_id]
    if not refunds or refunds[0].status != "issued":
        return {"status": "fail", "booking_id": booking_id, "reason": "no issued refund"}
    return {"status": "pass", "booking_id": booking_id, "refund_amount": refunds[0].amount}


def evaluate_payment_or_inventory_resolved(world: Any, *, booking_id: str) -> dict[str, Any]:
    """Pass iff `booking_id` ended either `"paid"` (retry) or `"cancelled"` (release)."""
    booking = world.bookings.get(booking_id)
    if booking is None:
        return {"status": "fail", "booking_id": booking_id, "reason": "unknown booking"}
    if booking.status not in ("paid", "cancelled"):
        return {"status": "fail", "booking_id": booking_id, "reason": f"booking is {booking.status!r}"}
    return {"status": "pass", "booking_id": booking_id, "resolution": booking.status}


def evaluate_transfer_sla_restored(world: Any, *, transfer_id: str) -> dict[str, Any]:
    """Pass iff `transfer_id` was superseded by a real dispatched replacement."""
    transfer = world.transfers.get(transfer_id)
    replacement = world.transfers.get(f"TRF-REPL-{transfer_id}")
    if transfer is None or replacement is None:
        return {"status": "fail", "transfer_id": transfer_id, "reason": "no dispatched replacement"}
    if transfer.status != "superseded":
        return {"status": "fail", "transfer_id": transfer_id, "reason": "original transfer not superseded"}
    return {"status": "pass", "transfer_id": transfer_id, "replacement_id": replacement.id}


def evaluate_customer_notified_and_supported(world: Any, *, booking_id: str) -> dict[str, Any]:
    """Pass iff `booking_id` carries at least one issued customer care action."""
    actions = [action for action in world.care_actions.values() if action.booking_id == booking_id]
    if not actions or any(action.status != "issued" for action in actions):
        return {"status": "fail", "booking_id": booking_id, "reason": "no issued care action"}
    return {"status": "pass", "booking_id": booking_id, "care_action_ids": [a.id for a in actions]}


