def render_worlds_processes_py() -> str:
    """Render `worlds/processes.py`: detectors, evaluators and REFERENCE_CASES."""
    lines = [_PROCESSES_PREAMBLE.rstrip("\n"), "", "REFERENCE_CASES: dict[str, ReferenceCase] = {"]
    for index, spec in enumerate(PROCESS_SPECS, start=1):
        case = CASE_BY_WORKFLOW_TYPE[spec.workflow_type]
        command_id = f"ref-{spec.workflow_id_prefix}-{index:02d}"
        lines.append(f"    {spec.workflow_type!r}: ReferenceCase(")
        lines.append(f"        workflow_type={spec.workflow_type!r},")
        lines.append(f"        role={spec.authority_role!r},")
        lines.append(f"        run_until_minutes={case.run_until_minutes!r},")
        lines.append(f"        disruption={case.disruption!r},")
        lines.append(f"        detect_target_id={case.detect_target_id!r},")
        lines.append(f"        command_id={command_id!r},")
        lines.append(f"        command_type={spec.command_type!r},")
        lines.append(f"        command_payload={case.command_payload!r},")
        lines.append("    ),")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


