    # -- generic causal-mutation helpers ----------------------------------

    def _created(
        self,
        event_type: str,
        record: Any,
        *,
        target_id: str | None = None,
        cause_event_id: str | None = None,
        trace_id: str | None = None,
        extra_payload: dict[str, Any] | None = None,
    ):
        payload = dict(extra_payload or {})
        payload.setdefault("id", record.id)
        event = self.runtime.emit(
            event_type,
            actor_id=record.id,
            target_id=target_id,
            cause_event_id=cause_event_id,
            trace_id=trace_id,
            payload=payload,
        )
        record.last_event_id = event.event_id
        return event

    def _apply(
        self,
        event_type: str,
        record: Any,
        changes: dict[str, Any],
        *,
        target_id: str | None = None,
        cause_event_id: str | None = None,
        trace_id: str | None = None,
        extra_payload: dict[str, Any] | None = None,
    ):
        payload = {**(extra_payload or {}), **changes}
        event = self.runtime.emit(
            event_type,
            actor_id=record.id,
            target_id=target_id,
            cause_event_id=cause_event_id,
            trace_id=trace_id,
            payload=payload,
        )
        for field, value in changes.items():
            setattr(record, field, value)
        record.last_event_id = event.event_id
        return event

