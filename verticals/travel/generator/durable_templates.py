def TravelRecoveryDetect(observation: dict) -> dict:
    """Activity, phase "detect": re-confirm the disrupted booking/party/
    flight identity named by the real sensor observation. Deterministic
    given `observation` -- no world reference, no I/O."""
    return {
        "disruption_id": observation["disruption_id"],
        "flight_id": observation["flight_id"],
        "booking_id": observation["booking_id"],
        "party_id": observation["party_id"],
        "observation": observation,
    }


def TravelRecoveryAssessImpact(detected: dict) -> dict:
    """Activity, phase "assess_impact": name every actor this disruption
    touches (booking, party, its member customers, the cancelled
    flight), purely from the carried-forward observation."""
    observation = detected["observation"]
    affected_actor_ids = [
        detected["booking_id"],
        detected["party_id"],
        *observation["member_customer_ids"],
        detected["flight_id"],
    ]
    return {
        **detected,
        "party_size": observation["party_size"],
        "member_customer_ids": list(observation["member_customer_ids"]),
        "destination_id": observation["destination_id"],
        "affected_actor_ids": affected_actor_ids,
    }


