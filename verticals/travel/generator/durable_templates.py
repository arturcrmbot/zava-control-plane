def _classify_decision(raw: Any) -> dict[str, Any]:
    """Classify one `TravelRecoveryApproval` external-event payload.

    Deliberately checks actor identity (`resolved_by == _APPROVAL_ROLE`)
    before the decision verb itself, so an approval from anyone other
    than the bound `head_of_operations` persona is rejected as
    `"wrong_actor"` even if it says "approve" -- never trusted as a
    valid approval. Any payload that is not a dict, or is missing either
    field, is `"malformed"` -- both are explicit terminal failures, never
    a silent fallback to some default decision.
    """
    if not isinstance(raw, dict):
        return {"outcome": "malformed", "decided_by": None}
    resolved_by = raw.get("resolved_by")
    decision = raw.get("decision")
    if not resolved_by or not decision:
        return {"outcome": "malformed", "decided_by": resolved_by}
    if resolved_by != _APPROVAL_ROLE:
        return {"outcome": "wrong_actor", "decided_by": resolved_by}
    if decision == "approve":
        return {"outcome": "approved", "decided_by": resolved_by}
    if decision == "reject":
        return {"outcome": "declined", "decided_by": resolved_by}
    return {"outcome": "malformed", "decided_by": resolved_by}


