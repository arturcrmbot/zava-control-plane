def TravelRecoveryBuildCommand(command_input: dict) -> dict:
    """Activity, phase "reaccommodate": build the one typed
    `reaccommodate_travellers` command from the approved/auto-approved
    option -- never mutates the world itself, only assembles the command
    a later `CommandGateway`/handler call will apply atomically.

    The parameter is deliberately not named ``data``: Azure Durable
    Functions' activity-trigger binding reserves that exact name and
    fails indexing with "Can't bind parameter 'data' to type
    'System.String'" (see Azure/Azure-Functions#1281)."""
    workflow_id = command_input["workflow_id"]
    trace_id = command_input["trace_id"]
    option = command_input["option"]
    decision = command_input["decision"]
    option_id = option["option_id"]
    payload = dict(option)
    payload["workflow_id"] = workflow_id
    payload["decision_id"] = f"DEC-{workflow_id}-{option_id}"
    payload["decision_outcome"] = decision.get("outcome")
    payload["decided_by"] = decision.get("decided_by")
    command = {
        "command_id": f"CMD-{workflow_id}-{option_id}",
        "trace_id": trace_id,
        "issued_by": _ISSUED_BY,
        "type": _COMMAND_TYPE,
        "payload": payload,
    }
    return {
        "command": command,
        "workflow_id": workflow_id,
        "trace_id": trace_id,
        "option_id": option_id,
        "decision": decision,
    }


def TravelRecoveryNotify(payload: dict) -> dict:
    """Activity, phase "notify": a deterministic notification record --
    never sends any real message, just the evidence of what would be
    communicated, covering both the successful-command and the
    no-command-authorised cases."""
    command = payload.get("command")
    decision = payload.get("decision") or {}
    if command is not None:
        summary = (
            f"Reaccommodation command {command['command_id']} issued for "
            f"option {command['payload'].get('option_id')} "
            f"(decided by {decision.get('decided_by')})"
        )
    else:
        summary = (
            f"Recovery not authorised for option {payload.get('option_id')}: "
            f"{decision.get('outcome')}"
        )
    return {
        "notified": True,
        "workflow_id": payload.get("workflow_id"),
        "channel": _ISSUED_BY,
        "summary": summary,
    }


def TravelRecoveryEvaluateIntent(payload: dict) -> dict:
    """Activity, phase "evaluate": the pure evaluation intent -- whether
    this recovery is expected to resolve its objective, and against
    which success event type -- read only from the already-assembled
    payload; never touches world state."""
    command = payload.get("command")
    return {
        "will_resolve_objective": command is not None,
        "expected_success_event_type": (
            "booking.reaccommodated" if command is not None else None
        ),
        "workflow_id": payload.get("workflow_id"),
        "option_id": (
            command["payload"]["option_id"] if command is not None else payload.get("option_id")
        ),
    }


def __ORCHESTRATOR_NAME__(context):
    """Real Azure Durable Functions orchestrator for flight-disruption
    recovery. A synchronous generator -- never `async` -- that performs
    no direct I/O, network, environment, randomness or wall-clock reads
    of its own: every fact flows in through `context.get_input()` or a
    `yield context.call_activity(...)` result, and the only "clock" it
    consults is `context.current_utc_datetime`, exactly per the Durable
    Functions Python programming model's replay-safety constraints.

    Phases: detect, assess_impact, search_alternatives, bound_options,
    approve_material_change (conditional HITL), reaccommodate, notify,
    evaluate. The `approve_material_change` phase first calls
    `context.set_custom_status(...)` -- the standard Durable Functions
    channel any status-query caller can read -- naming this exact phase
    and the exact external event a generic caller would raise, then races
    `wait_for_external_event` against `create_timer` via `task_any`
    whenever the top-ranked option requires approval, cancelling the
    still-pending timer the instant the approval event wins; a
    non-material, <=GBP-750 top option instead auto-approves through
    `TravelRecoveryAutoApprove`, never waits, and never sets a custom
    status at all (a truthful omission, not a fabricated "nothing to see"
    gate). Decline, timeout and malformed/wrong-actor approval responses
    are all explicit terminal failures: `TravelRecoveryBuildCommand` is
    skipped entirely and the final `command` is `None` -- never a silent
    fallback or a fabricated success. If the planner itself returns zero
    feasible options at all (every compatible replacement flight/transfer
    is already fully booked), this is likewise an explicit, deterministic
    `no_alternative` terminal outcome -- never an unguarded `options[0]`
    `IndexError` misclassified as an infrastructure fault: there is
    nothing to gate on HITL or auto-approve, so no timer/external-event
    wait is ever created, but Notify/EvaluateIntent still run truthfully
    against this no-command context.
    """
    input_data = context.get_input()
    workflow_id = input_data["workflow_id"]
    trace_id = input_data["trace_id"]
    objective_id = input_data.get("objective_id")
    observation = input_data["observation"]

    detected = yield context.call_activity("TravelRecoveryDetect", observation)
    impact = yield context.call_activity("TravelRecoveryAssessImpact", detected)
    options = yield context.call_activity("TravelRecoveryPlanOptions", impact)

    if not options:
        # No feasible replacement itinerary survived the planner's own
        # candidate flight/transfer capacity filter (every compatible
        # replacement is already fully booked for this party's size) -- a
        # real, expected outcome, never an infrastructure fault. Route
        # through this explicit, deterministic no-command terminal branch
        # rather than indexing options[0] (which would otherwise raise an
        # unguarded IndexError): there is no option left to gate on HITL
        # or auto-approve, so no custom status, timer or external-event
        # wait is ever created -- but Notify/EvaluateIntent still run
        # truthfully below against this no-command context, so this
        # outcome is always surfaced, never silently swallowed.
        top_option = None
        requires_approval = False
        decision = {"outcome": "no_alternative", "decided_by": None}
        command_payload = {
            "command": None,
            "workflow_id": workflow_id,
            "trace_id": trace_id,
            "option_id": None,
            "decision": decision,
        }
    else:
        top_option = options[0]
        requires_approval = bool(top_option["requires_approval"])

        if requires_approval:
            # Make the suspension observable through the standard Durable
            # custom-status channel (a generic Azure Durable Functions feature,
            # never a Travel-only side channel) *before* racing the wait, so any
            # generic caller polling the status-query endpoint -- including the
            # shared world_bridge -- can see the exact phase and the exact
            # external event name it would need to raise to resolve this gate.
            # The low-cost/auto-approved branch below never calls this: it never
            # suspends, so it truthfully omits the gate rather than faking one.
            context.set_custom_status({
                "phase": "approve_material_change",
                "external_event": _EXTERNAL_EVENT_NAME,
                "reason": (
                    f"option {top_option['option_id']} incremental cost GBP "
                    f"{top_option['incremental_cost_gbp']:.2f} or its "
                    "material_changes exceed the bounded auto-approve authority"
                ),
                "wait_kind": "operator_review",
                "wait_seconds": _HITL_WAIT_MINUTES * 60.0,
            })
            wait_task = context.wait_for_external_event(_EXTERNAL_EVENT_NAME)
            deadline = context.current_utc_datetime + timedelta(minutes=_HITL_WAIT_MINUTES)
            timer_task = context.create_timer(deadline)
            winner = yield context.task_any([wait_task, timer_task])
            if winner is wait_task:
                if not timer_task.is_completed:
                    timer_task.cancel()
                decision = _classify_decision(wait_task.result)
            else:
                decision = {"outcome": "timeout", "decided_by": None}
        else:
            decision = yield context.call_activity("TravelRecoveryAutoApprove", top_option)

        approved = decision.get("outcome") in ("approved", "auto_approved")
        if approved:
            command_payload = yield context.call_activity(
                "TravelRecoveryBuildCommand",
                {
                    "workflow_id": workflow_id,
                    "trace_id": trace_id,
                    "option": top_option,
                    "decision": decision,
                },
            )
        else:
            command_payload = {
                "command": None,
                "workflow_id": workflow_id,
                "trace_id": trace_id,
                "option_id": top_option["option_id"],
                "decision": decision,
            }

    notify_result = yield context.call_activity("TravelRecoveryNotify", command_payload)
    evaluation_intent = yield context.call_activity(
        "TravelRecoveryEvaluateIntent", command_payload
    )

    return _build_output(
        workflow_id=workflow_id,
        trace_id=trace_id,
        objective_id=objective_id,
        observation=observation,
        options=options,
        top_option=top_option,
        decision=decision,
        requires_approval=requires_approval,
        command=command_payload.get("command"),
        notify=notify_result,
        evaluation_intent=evaluation_intent,
    )


app.activity_trigger(input_name="observation")(TravelRecoveryDetect)
app.activity_trigger(input_name="detected")(TravelRecoveryAssessImpact)
app.activity_trigger(input_name="impact")(TravelRecoveryPlanOptions)
