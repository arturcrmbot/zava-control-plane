def _evaluation(workflow_id: str, evidence: Mapping[str, Any], app_state: Any) -> dict[str, Any] | None:
    command = evidence.get("command")
    if not isinstance(command, dict):
        return None
    cmd_payload = command.get("payload") if isinstance(command.get("payload"), dict) else {}
    option_id = cmd_payload.get("option_id") or evidence.get("option_id")
    if not option_id:
        return None
    evaluation_id = f"EVAL-{workflow_id}-{option_id}"
    world_service = getattr(app_state, "world_service", None)
    scenario = getattr(world_service, "scenario", None)
    recovery_evaluations = getattr(scenario, "recovery_evaluations", None) or {}
    recovery_eval = recovery_evaluations.get(evaluation_id)
    if recovery_eval is None:
        return None
    return {
        "evaluation_id": evaluation_id,
        "command_id": getattr(recovery_eval, "command_id", command.get("command_id")),
        "booking_id": getattr(recovery_eval, "booking_id", None),
        "party_id": getattr(recovery_eval, "party_id", None),
        "status": getattr(recovery_eval, "status", None),
        "criteria": _EVALUATION_CRITERIA,
    }


