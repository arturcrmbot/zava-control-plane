@dataclass(frozen=True)
class PartyPlan:
    """The deterministic, staggered pipeline timeline for one party.

    Every timestamp is an absolute simulation minute. A stage whose
    timestamp is None means the party's pipeline stops before that stage
    (used for the two parties that do not convert into a booking).
    `browse_at` always precedes `request_at`: every party's lead customer
    browses a destination before requesting a quote, and
    `browse_destination_id` names the destination they were looking at
    (not necessarily the one they eventually book, since ordinary browsing
    is exploratory).
    """

    party_id: str
    quote_id: str
    customer_id: str
    adviser_id: str
    price: float | None
    rooms: int
    browse_at: float
    browse_destination_id: str
