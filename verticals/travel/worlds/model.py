"""Dataclasses for the Travel vertical's deterministic, synthetic world.

Every record is a small, mutable dataclass carrying a real string "id" and
a "last_event_id" that always names the most recent causal journal event
that created or mutated it. There is no decorative or random state: every
field change in verticals.travel.worlds.scenario is paired with a journal
event that names the record (as actor or target) and carries the exact
new field values, so "last_event_id" evidence always matches final state.

This module is generated by verticals.travel.generator.world_templates.
Do not hand-edit -- change the generator template and regenerate via
`uv run python -m verticals.travel.generator`.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass
class Airport:
    """A real-world-shaped, synthetic UK departure airport."""

    id: str
    name: str
    city: str
    country: str
    last_event_id: str | None = None


@dataclass
class Destination:
    """A holiday destination package bookings travel to."""

    id: str
    name: str
    country: str
    last_event_id: str | None = None


@dataclass
class Supplier:
    """A third-party supplier: airline, hotelier or transfer operator."""

    id: str
    name: str
    kind: str  # "airline" | "hotelier" | "transfer_operator"
    last_event_id: str | None = None


@dataclass
class StaffMember:
    """A tour-operator staff member and the most recent action they took."""

    id: str
    name: str
    role: str  # "adviser" | "operations" | "destination" | "finance"
    last_action: str | None = None
    last_event_id: str | None = None


@dataclass
class Customer:
    """An individual customer. "status" tracks their own booking journey."""

    id: str
    name: str
    email: str
    status: str = "new"  # "new" -> "browsing" -> "engaged" -> "booked"
    last_event_id: str | None = None


@dataclass
class TravellingParty:
    """A group of customers travelling together on one itinerary.

    "state" is the party's lifecycle stage and "location" is its current
    real-world position (a home marker, an airport id, a flight id, a
    destination id, or a hotel id) -- both only ever change through a
    matching causal journal event.
    """

    id: str
    lead_customer_id: str
    member_customer_ids: tuple[str, ...]
    size: int
    state: str
    location: str
    last_event_id: str | None = None


@dataclass
class Flight:
    """A scheduled flight operated by a supplier airline.

    "base_fare_gbp" is the deterministic, reference-data-fixed GBP cost of
    reaccommodating one affected party onto this flight as a
    flight-disruption-recovery replacement -- read directly as an
    already-incremental figure (never subtracted against the disrupted
    flight's own fare), so it is only meaningful on a flight that is a
    candidate replacement. It is 0.0 on every flight seeded as an ordinary,
    never-disrupted itinerary leg.
    """

    id: str
    supplier_id: str
    origin_airport_id: str
    destination_id: str
    scheduled_departure: float
    scheduled_arrival: float
    capacity: int
    reserved: int
    status: str  # "scheduled" -> "departed" -> "arrived"
    base_fare_gbp: float = 0.0
    last_event_id: str | None = None


