@dataclass
class Booking:
    """A confirmed package booking converted from a quote.

    "status" is either the two-step "confirmed" -> "deposit_paid" -> "paid"
    ordinary sales journey, or a direct "confirmed" -> "paid" one-shot
    package sale (verticals.travel.actions.commands.confirm_package_booking).
    A booking can terminate as "cancelled" (cancellation-refund or a
    payment-exception release). "recovery_status" stays `None` unless a
    flight-disruption-recovery command has moved this booking onto a
    replacement flight/transfer, in which case it becomes
    `"reaccommodated"` -- real, queryable evidence distinct from the
    ordinary sales "status" progression above.
    """

    id: str
    quote_id: str
    party_id: str
    customer_id: str
    flight_id: str
    hotel_id: str
    allotment_id: str
    transfer_id: str
    rooms: int
    total_price: float
    status: str
    recovery_status: str | None = None
    last_event_id: str | None = None


